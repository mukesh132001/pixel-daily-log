// Every character is 3 wide plus 1 blank column.
export const textWidth = str => Math.max(0, String(str).length * 4 - 1);

// px(x, y, w, h, color) is the caller's pixel-painting function, so this works on any canvas.
// Lowercase letters are drawn as capitals; characters the font doesn't know are skipped.
export function drawText(px, str, x, y, color, shadow) {
  [...String(str).toUpperCase()].forEach((ch, i) => {
    const g = FONT[ch];
    if (!g) return;
    for (let r = 0; r < 5; r++) for (let c = 0; c < 3; c++) if (g[r][c] === "#") {
      if (shadow) px(x + i * 4 + c + 1, y + r + 1, 1, 1, shadow);
      px(x + i * 4 + c, y + r, 1, 1, color);
    }
  });
}
